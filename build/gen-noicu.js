#!/usr/bin/env node
/* =====================================================================
 * Seal Chat — build/gen-noicu.js   (makes src/main/noicu-ranges.js, 1.9.1)
 * ---------------------------------------------------------------------
 * The Android app's Node.js (nodejs-mobile) can't compile regular
 * expressions with Unicode property escapes (\p{…}). Seal Chat's Node-side
 * code therefore uses noicu.js: the \p{…} pattern where it works, otherwise
 * the SAME character class written out as explicit ranges. This script
 * writes those ranges by testing every code point against the original
 * classes, using this (desktop) Node.js's Unicode data.
 *   ELECTRON_RUN_AS_NODE=1 node_modules/electron/dist/electron build/gen-noicu.js
 *   (1.9.2: made with Electron's runtime — the one desktop users run — so the
 *    phone's fallback matches the desktop's \p{…} exactly. Run again after
 *    updating Electron.)
 * Based on the fix by the developer who found the Android crash.
 * ===================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
try { new RegExp('\\p{L}', 'u'); } catch { console.error('This Node.js has no ICU — use an official desktop Node.js'); process.exit(1); }

function expand(re) {
  const out = []; let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  const esc = c => c < 0x10000 ? '\\u' + c.toString(16).padStart(4, '0') : '\\u{' + c.toString(16) + '}';
  return out.map(([a, b]) => a === b ? esc(a) : esc(a) + '-' + esc(b)).join('');
}
const classes = {
  EMAIL_LOCAL: /^[^\p{C}\p{Z}@<>\\]$/u,                                          // openpgp isEmailAddress: name / domain characters
  EMAIL_LAST: /^[^\p{C}\p{Z}\p{P}]$/u,                                           //   …the last character
  PICT: /^\p{Extended_Pictographic}$/u,                                          // peer.js cleanEmoji
  EMOJI: /^[\p{Extended_Pictographic}\p{Emoji_Component}‍️⃣]$/u
};
let out = `/* Generated by build/gen-noicu.js from Unicode ${process.versions.unicode} (Node ${process.version}) — do not edit.
 * Explicit ranges equal to Seal Chat's \\p{…} classes, for runtimes without ICU (Android). See noicu.js. */\n'use strict';\nmodule.exports = {\n  unicode: ${JSON.stringify(process.versions.unicode)},\n`;
for (const [k, re] of Object.entries(classes)) out += `  ${k}: ${JSON.stringify(expand(re))},\n`;
out += '};\n';
const file = path.join(__dirname, '..', 'src', 'main', 'noicu-ranges.js');
fs.writeFileSync(file, out);
console.log('wrote', path.relative(process.cwd(), file), `(${(out.length / 1024).toFixed(1)} KB, Unicode ${process.versions.unicode})`);
